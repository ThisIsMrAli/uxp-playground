import { strFromU8, unzipSync, zipSync, type Zippable } from 'fflate';
import { compileModule, isScript, needsCompile, outputPath, REACT_MODULES, usesReact } from './compile';
import { parseManifest } from './manifest';
import { fileBytes, isBinaryContent, resolveRelative } from './files';
import { PLAYGROUND_BUILTINS } from './buildPreview';
import type { Project } from './types';

export interface ExportResult {
  zip: Uint8Array;
  fileName: string;
  files: string[];
  warnings: string[];
  /** Problems UDT would report when loading the folder (missing main, icons, referenced files). */
  problems: string[];
}

const VENDOR_SHIMS: Record<string, string> = {
  'vendor/react.js': "module.exports = require('./react-bundle.js').React;\n",
  'vendor/react-dom.js': "module.exports = require('./react-bundle.js').ReactDOM;\n",
  'vendor/react-dom-client.js': "module.exports = require('./react-bundle.js').ReactDOMClient;\n",
  'vendor/react-jsx-runtime.js': "module.exports = require('./react-bundle.js').jsxRuntime;\n"
};

/** Development-only files that do not belong in an installable plugin. */
const DEV_ONLY = /(^|\/)(package\.json|tsconfig(\.\w+)?\.json|(webpack|vite|rollup|babel|postcss|tailwind)\.config\.\w+|\.babelrc|\.gitignore|\.npmrc|\.eslintrc(\.\w+)?|\.prettierrc(\.\w+)?|\.editorconfig)$|\.d\.ts$/i;

export function slug(s: string) {
  return (s || 'uxp-plugin').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'uxp-plugin';
}

const STYLE_MODULE = (css: string, file: string) =>
  `// Generated by UXP Playground: injects ${file} (a bundler's style-loader does this in a webpack build).\n` +
  `var s = document.createElement('style');\ns.setAttribute('data-file', ${JSON.stringify(file)});\ns.textContent = ${JSON.stringify(css)};\ndocument.head.appendChild(s);\nmodule.exports = {};\n`;

/** Rewrites requires so the exported plugin loads without a bundler. */
export function rewriteForExport(fromPath: string, code: string, files: Record<string, string>, generated: Record<string, string>): string {
  const depth = fromPath.split('/').length - 1;
  const up = depth ? '../'.repeat(depth) : './';
  return code.replace(/require\(\s*(['"])([^'"]+)\1\s*\)/g, (whole, q: string, spec: string) => {
    if (REACT_MODULES[spec]) return `require(${q}${up}${REACT_MODULES[spec]}${q})`;
    if (!spec.startsWith('.')) return whole;
    const target = resolveRelative(fromPath, spec);
    if (target && /\.css$/i.test(target) && files[target] != null) {
      generated[target + '.js'] = STYLE_MODULE(files[target], target);
      return `require(${q}${spec}.js${q})`;
    }
    if (target && files[target] != null && (isBinaryContent(files[target]) || /\.svg$/i.test(target))) {
      generated[target + '.js'] = `// Generated by UXP Playground: path of ${target} for <img src>.\nmodule.exports = ${JSON.stringify(target)};\nmodule.exports.default = module.exports;\n`;
      return `require(${q}${spec}.js${q})`;
    }
    if (/\.(jsx|ts|tsx|mjs|cjs)$/i.test(spec)) return `require(${q}${outputPath(spec)}${q})`;
    return whole;
  });
}

/** Produces the files of an installable plugin folder (manifest.json at the root). */
export function exportFiles(p: Project, vendorBundle: string | null): { files: Record<string, string>; warnings: string[] } {
  const out: Record<string, string> = {};
  const generated: Record<string, string> = {};
  const warnings: string[] = [];
  const unresolved = new Set<string>();
  let reactUsed = false;
  for (const [path, code] of Object.entries(p.files)) {
    if (DEV_ONLY.test(path) && path !== 'manifest.json') continue;
    if (isBinaryContent(code)) {
      out[path] = code;
    } else if (isScript(path)) {
      let js = code;
      if (needsCompile(path, code)) {
        const c = compileModule(path, code);
        if (c.error) {
          // Keep the file (unchanged) so the plugin structure stays intact; UDT will show the same syntax error.
          warnings.push(`${path} has a syntax error and was exported unchanged: ${c.error.replace(/^Error transforming [^:]+: /, '')}`);
          out[outputPath(path)] = code;
          continue;
        }
        js = c.code;
      }
      if (usesReact(js)) reactUsed = true;
      for (const m of js.matchAll(/\brequire\(\s*['"]([^'"./][^'"]*)['"]\s*\)/g)) {
        const name = m[1].replace(/^adobe:/, '');
        if (!PLAYGROUND_BUILTINS.includes(name) && !name.startsWith('plugin:')) unresolved.add(name);
      }
      out[outputPath(path)] = rewriteForExport(path, js, p.files, generated);
    } else if (/\.html?$/i.test(path)) {
      out[path] = code.replace(/(<script\b[^>]*\bsrc\s*=\s*["'])([^"']+)(["'])/gi, (_w, a: string, src: string, b: string) =>
        /^https?:/i.test(src) ? a + src + b : a + outputPath(src) + b
      );
    } else if (path === 'manifest.json') {
      const parsed = parseManifest(code);
      if (parsed.ok && typeof parsed.value.main === 'string' && isScript(parsed.value.main)) {
        parsed.value.main = outputPath(parsed.value.main);
        out[path] = JSON.stringify(parsed.value, null, 2) + '\n';
      } else {
        out[path] = code;
      }
    } else {
      out[path] = code;
    }
  }
  for (const [k, v] of Object.entries(generated)) if (out[k] == null) out[k] = v;
  if (unresolved.size) warnings.push(`npm packages need a bundler and are not included: ${[...unresolved].sort().join(', ')}`);
  if (reactUsed) {
    if (!vendorBundle) warnings.push('React is used but the vendor bundle is not available; the plugin will not load.');
    else {
      out['vendor/react-bundle.js'] = vendorBundle;
      Object.assign(out, VENDOR_SHIMS);
    }
  }
  out['PLAYGROUND-README.txt'] = [
    `${p.name} — exported from UXP Playground`,
    '',
    'How to load it:',
    '1. Unzip this archive into a folder.',
    '2. Open the UXP Developer Tool (UDT), choose "Add Plugin" and select manifest.json in that folder.',
    '3. Start your host app, then choose Load in UDT.',
    '',
    'JSX/TypeScript/ES-module files were compiled to plain CommonJS .js files.',
    reactUsed ? 'React 19 is included as vendor/react-bundle.js (production build).' : '',
    Object.keys(generated).length ? 'CSS and image imports were turned into small *.css.js / *.png.js modules.' : '',
    'Development files (package.json, bundler configs, .d.ts) were left out.',
    'The playground preview was an approximation. Behaviour in the real host can differ.',
    ''
  ].filter((l, i, a) => l !== '' || a[i - 1] !== '').join('\n');
  return { files: out, warnings };
}

/** Checks an exported plugin folder the way UDT would see it. */
export function validatePluginFiles(files: Record<string, string | Uint8Array>): string[] {
  const problems: string[] = [];
  const names = Object.keys(files);
  const text = (k: string) => (typeof files[k] === 'string' ? (files[k] as string) : strFromU8(files[k] as Uint8Array));
  if (files['manifest.json'] == null) return ['manifest.json is not at the root of the plugin folder'];
  let m: any;
  try {
    m = JSON.parse(text('manifest.json'));
  } catch {
    return ['manifest.json is not valid JSON'];
  }
  for (const k of ['id', 'name', 'version', 'host']) if (m[k] == null) problems.push(`manifest.json has no "${k}"`);
  const main = typeof m.main === 'string' ? m.main.replace(/^\.\//, '') : null;
  if (main && files[main] == null) problems.push(`"main" file is missing: ${main}`);
  const icons = [...(Array.isArray(m.icons) ? m.icons : []), ...((Array.isArray(m.entrypoints) ? m.entrypoints : []).flatMap((e: any) => (e && Array.isArray(e.icons) ? e.icons : [])))];
  for (const ic of icons) {
    if (!ic || typeof ic.path !== 'string') continue;
    const path = ic.path.replace(/^\.\//, '');
    const scales: number[] = Array.isArray(ic.scale) && ic.scale.length ? ic.scale : [1];
    const found = names.includes(path) || scales.some((s) => names.includes(path.replace(/(\.\w+)$/, `@${s}x$1`)));
    if (!found) problems.push(`icon is missing: ${path}`);
  }
  if (main && files[main] != null && /\.html?$/i.test(main)) {
    const html = text(main);
    for (const mm of html.matchAll(/<(?:script|img)\b[^>]*\bsrc\s*=\s*["']([^"']+)["']/gi)) {
      const p = resolveRelative(main, mm[1]);
      if (p && files[p] == null) problems.push(`${main} references a missing file: ${p}`);
    }
    for (const mm of html.matchAll(/<link\b[^>]*\bhref\s*=\s*["']([^"']+)["']/gi)) {
      const p = resolveRelative(main, mm[1]);
      if (p && files[p] == null) problems.push(`${main} references a missing file: ${p}`);
    }
  }
  return [...new Set(problems)];
}

export function buildPluginZip(p: Project, vendorBundle: string | null): ExportResult {
  const { files, warnings } = exportFiles(p, vendorBundle);
  const tree: Zippable = {};
  for (const [path, content] of Object.entries(files)) {
    const binary = isBinaryContent(content);
    tree[path] = [fileBytes(content), { level: binary ? 0 : 6, mtime: new Date('2026-01-01T00:00:00Z') }];
  }
  const zip = zipSync(tree);
  const m = parseManifest(p.files['manifest.json']).value;
  const fileName = `${slug(m.name || p.name)}-${m.version || '1.0.0'}.zip`;
  const problems = validatePluginFiles(Object.fromEntries(Object.entries(files).map(([k, v]) => [k, isBinaryContent(v) ? fileBytes(v) : v])));
  return { zip, fileName, files: Object.keys(files).sort(), warnings, problems };
}

/** Reads a zip (or .ccx) into raw files for the importer. */
export function readZip(bytes: Uint8Array): Record<string, Uint8Array> {
  const out: Record<string, Uint8Array> = {};
  const all = unzipSync(bytes);
  for (const [k, v] of Object.entries(all)) if (!k.endsWith('/')) out[k] = v;
  return out;
}
