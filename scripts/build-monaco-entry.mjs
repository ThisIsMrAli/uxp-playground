// Builds src/generated/monaco-entry.js: monaco-editor's own ESM entry (esm/vs/index.js) minus the 80+ language
// grammars the playground never shows. Generated from the installed version so it stays in sync on upgrades.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(resolve(root, 'node_modules/monaco-editor/esm/vs/index.js'), 'utf8');
const KEEP = new Set(['css', 'html', 'javascript', 'typescript', 'markdown', 'scss', 'less', 'xml', 'yaml', 'shell']);
let kept = 0;
let dropped = 0;
const out = src
  .split('\n')
  .filter((line) => {
    const m = /languages\/definitions\/([\w-]+)\/register\.js/.exec(line);
    if (!m) return true;
    if (KEEP.has(m[1])) return kept++, true;
    dropped++;
    return false;
  })
  .filter((line) => !/monaco-lsp-client|export \{ index as lsp \}/.test(line))
  .map((line) => line.replace(/(['"])\.\/(?!\.)/g, '$1../../node_modules/monaco-editor/esm/vs/'))
  .join('\n');
mkdirSync(resolve(root, 'src/generated'), { recursive: true });
writeFileSync(resolve(root, 'src/generated/monaco-entry.js'), '// Generated by scripts/build-monaco-entry.mjs. Do not edit.\n' + out);
console.log(`monaco-entry: kept ${kept} language grammars, dropped ${dropped}`);
