// Refresh the checked-in facts from an AdobeDocs/uxp-premiere-pro checkout.
// node scripts/build-premiere-versions.mjs /path/to/uxp-premiere-pro
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';

const checkout = process.argv[2];
if (!checkout) throw new Error('Pass the path to an AdobeDocs/uxp-premiere-pro checkout.');
const reference = join(checkout, 'src/pages/ppro-reference');
const commit = execFileSync('git', ['-C', checkout, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const later = /^2[6-9]\.\d+(?:\.\d+)?$/;
const versions = {};

function record(name, version, page, section) {
  if (!later.test(version) || Object.hasOwn(versions, name)) return;
  versions[name] = [version, `${page}${section ? `#${section.toLowerCase()}` : ''}`];
}

for (const file of readdirSync(join(reference, 'classes')).filter((name) => name.endsWith('.md'))) {
  const source = readFileSync(join(reference, 'classes', file), 'utf8');
  const owner = /^# (\w+)$/m.exec(source)?.[1];
  if (!owner) continue;
  const page = `classes/${file.slice(0, -3)}`;
  let section = '';
  let member = '';
  for (const line of source.split('\n')) {
    if (line.startsWith('## ')) {
      section = line.slice(3).trim();
      member = section === 'Constructor' ? 'constructor' : '';
    } else if (line.startsWith('### ')) {
      member = line.slice(4).trim();
    } else {
      const since = /^Since: \*\*([\d.]+)\*\*\s*$/.exec(line)?.[1];
      if (since && (!section || member)) record(member ? `${owner}.${member}` : owner, since, page, member);
      const prop = section === 'Properties' && /^\| (\w+) \| [^|]+ \| [^|]+ \| ([\d.]+) \|/.exec(line);
      if (prop) record(`${owner}.${prop[1]}`, prop[2], page, 'properties');
    }
  }
}

const constants = readFileSync(join(reference, 'constants/index.md'), 'utf8');
let enumeration = '';
for (const line of constants.split('\n')) {
  if (line.startsWith('### ')) enumeration = line.slice(4).trim();
  if (!enumeration) continue;
  const since = /^Since: \*\*([\d.]+)\*\*\s*$/.exec(line)?.[1];
  if (since) record(`Constants.${enumeration}`, since, 'constants', enumeration);
  const member = /^\| (\w+) \| ([\d.]+) \|/.exec(line);
  if (member) record(`${enumeration}.${member[1]}`, member[2], 'constants', enumeration);
}

// These existing properties were deprecated in 26.5. The class page lists that
// version in their table, but the changelog confirms availability before 26.5.
delete versions['Media.duration'];
delete versions['Media.start'];
// The API now reports these properties as an enum. Reading the number predates 27.0.
delete versions['ClipProjectItem.type'];
delete versions['FolderItem.type'];
// Some new methods have no Since line in their API reference section.
record('Transcript.isLanguagePackAvailable', '26.5', 'classes/transcript', 'isLanguagePackAvailable');
record('Transcript.transcribeClipProjectItem', '26.5', 'classes/transcript', 'transcribeClipProjectItem');

const entries = Object.entries(versions).sort(([a], [b]) => a.localeCompare(b));
if (!entries.length) throw new Error('No Premiere API versions found. Check the source format.');
const output = [
  `// Adobe Premiere Pro API reference snapshot ${commit}.`,
  '// Generated by scripts/build-premiere-versions.mjs.',
  'export const PREMIERE_API_VERSIONS: Readonly<Record<string, readonly [version: string, reference: string]>> = {',
  ...entries.map(([name, value]) => `  ${JSON.stringify(name)}: ${JSON.stringify(value)},`),
  '};',
  ''
].join('\n');
writeFileSync(new URL('../src/core/premiereVersions.ts', import.meta.url), output);
